import { createHash } from 'node:crypto'
import { appendFileSync, existsSync, mkdirSync, readdirSync } from 'node:fs'
import { basename, join } from 'node:path'

/** Mission records (plan § Mission records, D4): one plain Markdown note per mission, written
 *  only by the app, append-only. On for every space: by default under the app's own data
 *  folder (`defaultRecordsDir`), or in a folder the space settings name instead. */

/** `<base>/<repo name>-<short hash of its path>`: readable, and two repos that share a name
 *  (two checkouts called "app") never mix their notes. */
export function defaultRecordsDir(base: string, repoRoot: string): string {
  const hash = createHash('sha1').update(repoRoot).digest('hex').slice(0, 6)
  return join(base, `${basename(repoRoot) || 'repo'}-${hash}`)
}

export function recordPath(dir: string, mission: string, createdAt: number): string {
  const date = new Date(createdAt).toISOString().slice(0, 10)
  return join(dir, `${date} - ${mission}.md`)
}

/** Earlier missions' notes in `dir`, newest first, at most `limit`. Never throws. */
export function pastRecords(dir: string | null, exclude: string | null = null, limit = 20): string[] {
  if (!dir || !existsSync(dir)) return []
  try {
    return readdirSync(dir)
      .filter((f) => /^\d{4}-\d{2}-\d{2} - .+\.md$/.test(f))
      .map((f) => join(dir, f))
      .filter((p) => p !== exclude)
      .sort()
      .reverse()
      .slice(0, limit)
  } catch {
    return []
  }
}

export function appendRecord(
  dir: string,
  m: { name: string; repoPath: string; createdAt: number; brief: string | null },
  heading: string,
  body: string
): string {
  mkdirSync(dir, { recursive: true })
  const file = recordPath(dir, m.name, m.createdAt)
  const now = new Date()
  if (!existsSync(file)) {
    const date = new Date(m.createdAt).toISOString().slice(0, 10)
    appendFileSync(
      file,
      [
        '---',
        `project: ${m.repoPath.split(/[\\/]/).pop()}`,
        'type: mission',
        `created: ${date}`,
        '---',
        '',
        `<!-- AI-generated by The ORC — ${date} -->`,
        '',
        `# ${date} - Mission ${m.name}`,
        '',
        `Repository: \`${m.repoPath}\``,
        ''
      ].join('\n')
    )
  }
  appendFileSync(file, `\n## ${heading} (${now.toISOString().slice(0, 16).replace('T', ' ')})\n\n${body.trim()}\n`)
  return file
}
